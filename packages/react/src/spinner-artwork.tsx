const generalLoopMs = 1600;
const generalStaggerMs = generalLoopMs / frames.default.length;

// Keep the supplied dot motion unchanged; only stagger its phase evenly.
const generalFrames = frames.default.map((dot) => ({
  ...frames.default[0],
  transform: dot.transform,
}));

export function SpinnerArtwork({
  variant,
  animated,
}: {
  variant: 'default' | 'button';
  animated: boolean;
}) {
  const button = variant === 'button';
  const duration = button ? '1.92s' : `${generalLoopMs}ms`;
  const animation = {
    dur: duration,
    repeatCount: 'indefinite',
    begin: '0s',
    fill: 'freeze',
    calcMode: 'spline',
  } as const;

  return (
    <svg
      aria-hidden="true"
      focusable="false"
      viewBox={button ? '140 140 200 200' : '100 100 200 200'}
      className="size-full"
      fill="currentColor"
    >
      {(button ? frames.button : generalFrames).map((frame, index) => (
        <g key={index} transform={frame.transform}>
          <g opacity={animated ? (button ? 0.15 : 0) : 0.65}>
            {animated ? (
              <animate
                {...animation}
                begin={button ? '0s' : `${index * generalStaggerMs - generalLoopMs}ms`}
                attributeName="opacity"
                values={frame.opacity}
                keyTimes={frame.keyTimes}
                keySplines={frame.splines}
              />
            ) : null}
            <g
              transform={`translate(0,${animated ? (button ? -80 : -88.32) : button ? -67.2 : -69.12})`}
            >
              {animated ? (
                <animateTransform
                  {...animation}
                  begin={button ? '0s' : `${index * generalStaggerMs - generalLoopMs}ms`}
                  type="translate"
                  attributeName="transform"
                  values={frame.move}
                  keyTimes={frame.keyTimes}
                  keySplines={frame.moveSplines}
                />
              ) : null}
              <g transform={`scale(${animated ? (button ? 0.45 : 0.4) : 0.75})`}>
                {animated ? (
                  <animateTransform
                    {...animation}
                    begin={button ? '0s' : `${index * generalStaggerMs - generalLoopMs}ms`}
                    type="scale"
                    attributeName="transform"
                    values={frame.scale}
                    keyTimes={frame.keyTimes}
                    keySplines={frame.splines}
                  />
                ) : null}
                <circle r={button ? 12.8 : 10.56} />
              </g>
            </g>
          </g>
        </g>
      ))}
    </svg>
  );
}
